function getPreset(id) {
    return PRESETS[id] || PRESETS["catppuccin-mocha"]
}

function labelFor(id, autoSourceLabel) {
    if (!id || id === "auto") {
        return autoSourceLabel ? `Auto · ${autoSourceLabel}` : "Auto"
    }
    return PRESETS[id] ? PRESETS[id].label : id
}

function nextThemeId(currentId) {
    const idx = ORDER.indexOf(currentId || "auto")
    return ORDER[(idx + 1) % ORDER.length]
}
